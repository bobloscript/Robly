#!/usr/bin/env python3
"""Generate src/core/LucideData.lua — the Lucide icon sprite map for Roblox.

Source: latte-soft/lucide-roblox release bundle (MIT), which uploads the
Lucide icon set (ISC, https://lucide.dev) to Roblox as 48 px sprite sheets.
We only keep the 48 px map: name -> sheet asset id + offset on the sheet.

    python3 tools/gen_lucide.py                 # downloads the latest release
    python3 tools/gen_lucide.py path/to.luau    # or uses a local copy
"""
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "core" / "LucideData.lua"
URL = "https://github.com/latte-soft/lucide-roblox/releases/latest/download/lucide-roblox.luau"


def main() -> None:
    if len(sys.argv) > 1:
        source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        source = urllib.request.urlopen(URL).read().decode("utf-8")
    version = re.search(r"Lucide Version: ([\d.]+)", source)
    package = re.search(r"Package Version: ([\d.]+)", source)
    compact = re.sub(r"\s+", "", source)
    entries = re.findall(
        r"(?:\['([^']+)'\]|(?<=[{,])([A-Za-z_]\w*))=\{(\d+),\{48,48\},\{(\d+),(\d+)\}\}", compact
    )
    icons = {}
    for quoted, bare, asset, x, y in entries:
        icons[quoted or bare] = (int(asset), int(x), int(y))
    if len(icons) < 1000:
        sys.exit(f"only {len(icons)} icons parsed — the bundle format probably changed")
    sheets = sorted({asset for asset, _, _ in icons.values()})
    index = {asset: i + 1 for i, asset in enumerate(sheets)}

    lines = [
        "-- Lucide icons (https://lucide.dev, ISC License) as Roblox sprite sheets,",
        "-- from latte-soft/lucide-roblox (MIT License, Copyright (c) 2023 Latte Softworks).",
        f"-- Lucide {version.group(1) if version else '?'} · lucide-roblox {package.group(1) if package else '?'}",
        "-- Generated by tools/gen_lucide.py — do not edit by hand.",
        "-- Icons[name] = { sheet index, x offset, y offset }; every icon is 48×48.",
        "",
        "return {",
        f'\tVersion = "{version.group(1) if version else ""}",',
        "\tSize = 48,",
        "\tSheets = { " + ", ".join(str(s) for s in sheets) + " },",
        "\tIcons = {",
    ]
    for name in sorted(icons):
        asset, x, y = icons[name]
        lines.append(f'\t\t["{name}"] = {{ {index[asset]}, {x}, {y} }},')
    lines += ["\t},", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(icons)} icons on {len(sheets)} sheets")


if __name__ == "__main__":
    main()
